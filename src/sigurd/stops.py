def remove_stops(tokens: list[str], stops: tuple[str, ...] | frozenset[str]) -> list[str]:
    """Remove the stop words from tokens, ignoring case.

    >>> remove_stops(["Hér", "hefr", "upp", "ok", "segir", "frá", "þeim", "manni"], OLD_NORSE_STOPS)
    ['hefr', 'segir', 'manni']
    >>> remove_stops(["von", "heleden", "lobebæren"], MIDDLE_HIGH_GERMAN_STOPS)
    ['heleden', 'lobebæren']
    """
    stop_set = frozenset(stops)
    return [token for token in tokens if token.lower() not in stop_set]
